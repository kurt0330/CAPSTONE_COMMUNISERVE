-- ── 7a. Customer books a fixed service or opens a custom negotiation ───
CREATE OR REPLACE FUNCTION "public"."create_service_request"(
    "p_provider_id"         bigint,
    "p_request_type"        text,
    "p_provider_service_id" bigint  DEFAULT NULL,
    "p_description"         text    DEFAULT NULL,
    "p_street"              text    DEFAULT NULL,
    "p_barangay"            text    DEFAULT NULL,
    "p_proposed_price"      numeric DEFAULT NULL,
    "p_payment_structure"   text    DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET "search_path" = "public"
AS $$
DECLARE
    v_customer_id  bigint;
    v_trade        text;
    v_price        numeric(10,2);
    v_service_name text;
    v_description  text := NULLIF(btrim(p_description), '');
    v_job_id       bigint;
BEGIN
    SELECT c.customer_id INTO v_customer_id
    FROM customers c JOIN users u ON u.user_id = c.user_id
    WHERE u.auth_id = auth.uid();
    IF v_customer_id IS NULL THEN
        RAISE EXCEPTION 'Only resident accounts can send requests.';
    END IF;

    SELECT trade_category INTO v_trade
    FROM providers WHERE provider_id = p_provider_id AND admin_status = 'Approved';
    IF v_trade IS NULL THEN
        RAISE EXCEPTION 'This provider is not available.';
    END IF;

    IF NULLIF(btrim(p_barangay), '') IS NULL THEN
        RAISE EXCEPTION 'Please choose the barangay.';
    END IF;

    PERFORM set_config('communiserve.trusted_write', 'on', true);

    IF p_request_type = 'fixed' THEN
        SELECT ps.price, sc.service_name INTO v_price, v_service_name
        FROM provider_services ps
        JOIN service_catalog sc ON sc.catalog_id = ps.catalog_id
        WHERE ps.provider_service_id = p_provider_service_id
          AND ps.provider_id = p_provider_id
          AND ps.is_active;
        IF v_price IS NULL THEN
            RAISE EXCEPTION 'That service is no longer offered.';
        END IF;

        INSERT INTO job_requests (
            customer_id, provider_id, service_description, service_street, service_barangay,
            job_status, request_type, provider_service_id, service_name, agreed_price
        ) VALUES (
            v_customer_id, p_provider_id, COALESCE(v_description, v_service_name),
            NULLIF(btrim(p_street), ''), btrim(p_barangay),
            'Pending', 'fixed', p_provider_service_id, v_service_name, v_price
        )
        RETURNING job_id INTO v_job_id;

    ELSIF p_request_type = 'custom' THEN
        IF v_description IS NULL THEN
            RAISE EXCEPTION 'Please describe the work you need.';
        END IF;
        IF p_proposed_price IS NULL OR p_proposed_price <= 0 OR p_proposed_price > 1000000 THEN
            RAISE EXCEPTION 'Please enter a valid proposed price.';
        END IF;
        -- COALESCE: a NULL structure must fail this check, not slip past NOT IN.
        IF v_trade = 'Carpenter' AND COALESCE(p_payment_structure, '') NOT IN ('arawan', 'pakyawan') THEN
            RAISE EXCEPTION 'Choose Arawan (daily rate) or Pakyawan (per project).';
        END IF;
        IF v_trade <> 'Carpenter' AND p_payment_structure IS NOT NULL THEN
            RAISE EXCEPTION 'Payment structure only applies to Panday requests.';
        END IF;

        INSERT INTO job_requests (
            customer_id, provider_id, service_description, service_street, service_barangay,
            job_status, request_type, service_name, payment_structure
        ) VALUES (
            v_customer_id, p_provider_id, v_description,
            NULLIF(btrim(p_street), ''), btrim(p_barangay),
            'Pending', 'custom', 'Custom Service', p_payment_structure
        )
        RETURNING job_id INTO v_job_id;

        INSERT INTO job_offers (job_id, offered_by, amount)
        VALUES (v_job_id, 'customer', round(p_proposed_price, 2));

    ELSE
        RAISE EXCEPTION 'Unknown request type.';
    END IF;

    RETURN v_job_id;
END;
$$;

