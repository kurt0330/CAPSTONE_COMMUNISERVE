-- ═══════════════════════════════════════════════════════════════════════
--  CommuniServe — pre-set services, fixed pricing & custom negotiation
--
--  1. service_catalog    trade-specific pre-set services (seeded below)
--  2. provider_services  a provider's activated pre-sets + their fixed price
--  3. job_requests       + request_type, provider_service_id, service_name,
--                          agreed_price, payment_structure (all nullable —
--                          NULL request_type = legacy free-text request)
--  4. job_offers         bidding history for "Custom Service" requests
--  5. guard trigger      pricing fields can only be written by the
--                          SECURITY DEFINER functions below
--  6. functions          create_service_request, respond_to_job_offer,
--                          get_customer_jobs, get_provider_jobs
--
--  NEGOTIATION STATE MACHINE (no change to the job_status CHECK):
--    custom request created  → job_status 'Pending', customer's offer #1
--    whoever did NOT make the latest offer may:
--      accept   → 'Accepted', agreed_price = latest offer
--      decline  → 'Declined' (provider) / 'Cancelled' (customer)
--      counter  → new offer row, turn passes to the other party
--  Fixed requests keep the existing flow: 'Pending' → provider Accept /
--  Decline, with agreed_price snapshotted from the provider's price.
--
--  ADDITIVE ONLY — no existing column, constraint, policy or row is
--  dropped or rewritten. Idempotent — safe to re-run in the SQL Editor.
-- ═══════════════════════════════════════════════════════════════════════


