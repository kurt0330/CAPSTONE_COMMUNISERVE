CREATE OR REPLACE FUNCTION "public"."get_customer_jobs"()
RETURNS TABLE (
    "job_id"              bigint,
    "provider_id"         bigint,
    "provider_name"       text,
    "trade_category"      text,
    "request_type"        text,
    "service_name"        text,
    "service_description" text,
    "service_street"      text,
    "service_barangay"    text,
    "job_status"          text,
    "agreed_price"        numeric,
    "payment_structure"   text,
    "requested_at"        timestamptz,
    "offers"              jsonb
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET "search_path" = "public"
AS $$
    SELECT
        j.job_id,
        j.provider_id,
        pu.full_name::text,
        p.trade_category::text,
        j.request_type,
        j.service_name::text,
        j.service_description::text,
        j.service_street::text,
        j.service_barangay::text,
        j.job_status::text,
        j.agreed_price,
        j.payment_structure,
        j.requested_at,
        COALESCE((
            SELECT jsonb_agg(jsonb_build_object(
                       'offer_id', o.offer_id, 'offered_by', o.offered_by,
                       'amount', o.amount, 'note', o.note, 'created_at', o.created_at)
                   ORDER BY o.created_at, o.offer_id)
            FROM job_offers o WHERE o.job_id = j.job_id
        ), '[]'::jsonb)
    FROM job_requests j
    JOIN providers p  ON p.provider_id = j.provider_id
    JOIN users pu     ON pu.user_id    = p.user_id
    JOIN customers c  ON c.customer_id = j.customer_id
    JOIN users cu     ON cu.user_id    = c.user_id
    WHERE cu.auth_id = auth.uid()
    ORDER BY j.requested_at DESC;
$$;

