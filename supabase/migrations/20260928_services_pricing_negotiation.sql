REVOKE EXECUTE ON FUNCTION "public"."create_service_request"(bigint, text, bigint, text, text, text, numeric, text) FROM PUBLIC, "anon";
GRANT  EXECUTE ON FUNCTION "public"."create_service_request"(bigint, text, bigint, text, text, text, numeric, text) TO "authenticated";

-- ── 7b. Either party answers the latest offer on a custom request ──────
CREATE OR REPLACE FUNCTION "public"."respond_to_job_offer"(
    "p_job_id" bigint,
    "p_action" text,
    "p_amount" numeric DEFAULT NULL,
    "p_note"   text    DEFAULT NULL
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET "search_path" = "public"
AS $$
DECLARE
    v_job    job_requests%ROWTYPE;
    v_last   job_offers%ROWTYPE;
    v_actor  text;
    v_status text;
BEGIN
    -- Row lock: two quick taps (or both parties at once) can't both win.
    SELECT * INTO v_job FROM job_requests WHERE job_id = p_job_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Request not found.';
    END IF;

    IF EXISTS (SELECT 1 FROM customers c JOIN users u ON u.user_id = c.user_id
               WHERE c.customer_id = v_job.customer_id AND u.auth_id = auth.uid()) THEN
        v_actor := 'customer';
    ELSIF EXISTS (SELECT 1 FROM providers p JOIN users u ON u.user_id = p.user_id
                  WHERE p.provider_id = v_job.provider_id AND u.auth_id = auth.uid()) THEN
        v_actor := 'provider';
    ELSE
        RAISE EXCEPTION 'This is not your request.';
    END IF;

    IF v_job.request_type IS DISTINCT FROM 'custom' THEN
        RAISE EXCEPTION 'Only custom requests can be negotiated.';
    END IF;
    IF v_job.job_status <> 'Pending' THEN
        RAISE EXCEPTION 'This negotiation is already closed.';
    END IF;

    SELECT * INTO v_last FROM job_offers
    WHERE job_id = p_job_id
    ORDER BY created_at DESC, offer_id DESC
    LIMIT 1;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'There is no offer to respond to.';
    END IF;
    IF v_last.offered_by = v_actor THEN
        RAISE EXCEPTION 'Waiting for the other party to respond to your offer.';
    END IF;

    PERFORM set_config('communiserve.trusted_write', 'on', true);

    IF p_action = 'accept' THEN
        UPDATE job_requests
        SET job_status = 'Accepted', agreed_price = v_last.amount, accepted_at = now()
        WHERE job_id = p_job_id;
        RETURN 'Accepted';

    ELSIF p_action = 'decline' THEN
        v_status := CASE WHEN v_actor = 'provider' THEN 'Declined' ELSE 'Cancelled' END;
        UPDATE job_requests SET job_status = v_status WHERE job_id = p_job_id;
        RETURN v_status;

    ELSIF p_action = 'counter' THEN
        IF p_amount IS NULL OR p_amount <= 0 OR p_amount > 1000000 THEN
            RAISE EXCEPTION 'Please enter a valid amount.';
        END IF;
        INSERT INTO job_offers (job_id, offered_by, amount, note)
        VALUES (p_job_id, v_actor, round(p_amount, 2), NULLIF(btrim(p_note), ''));
        RETURN 'Pending';

    ELSE
        RAISE EXCEPTION 'Unknown action.';
    END IF;
END;
$$;

