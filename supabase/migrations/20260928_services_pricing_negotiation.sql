    USING ("public"."is_admin"());


-- ═══════════════════════════════════════════════════════════════════════
--  6. GUARD — pricing can't be forged through the plain table policies
--
--  The existing "Customers create own requests" INSERT policy and
--  "Providers update own requests" UPDATE policy would otherwise let a
--  client write any agreed_price. This trigger rejects pricing writes and
--  custom-request status changes unless they come from the SECURITY
--  DEFINER functions below, which set a transaction-local flag.
--  Legacy inserts (no pricing columns) and the provider's
--  Accept/Decline/Start/Complete on fixed requests are unaffected.
-- ═══════════════════════════════════════════════════════════════════════

CREATE OR REPLACE FUNCTION "public"."guard_job_pricing"()
RETURNS trigger
LANGUAGE plpgsql
SET "search_path" = "public"
AS $$
BEGIN
    IF current_setting('communiserve.trusted_write', true) = 'on' THEN
        RETURN NEW;
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NEW.request_type IS NOT NULL OR NEW.agreed_price IS NOT NULL
           OR NEW.provider_service_id IS NOT NULL OR NEW.payment_structure IS NOT NULL
           OR NEW.service_name IS NOT NULL THEN
            RAISE EXCEPTION 'Priced requests must be created through create_service_request()';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.request_type        IS DISTINCT FROM OLD.request_type
       OR NEW.agreed_price     IS DISTINCT FROM OLD.agreed_price
       OR NEW.provider_service_id IS DISTINCT FROM OLD.provider_service_id
       OR NEW.payment_structure IS DISTINCT FROM OLD.payment_structure
       OR NEW.service_name     IS DISTINCT FROM OLD.service_name THEN
        RAISE EXCEPTION 'Pricing fields can only change through the negotiation functions';
    END IF;

    IF OLD.request_type = 'custom' AND OLD.job_status = 'Pending'
       AND NEW.job_status IS DISTINCT FROM OLD.job_status THEN
        RAISE EXCEPTION 'Custom requests are settled through respond_to_job_offer()';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS "guard_job_pricing" ON "public"."job_requests";
CREATE TRIGGER "guard_job_pricing"
    BEFORE INSERT OR UPDATE ON "public"."job_requests"
    FOR EACH ROW EXECUTE FUNCTION "public"."guard_job_pricing"();


